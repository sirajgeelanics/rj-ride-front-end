type TranslationKey = keyof typeof translations.en;

// `language` stays a parameter (unused) rather than being dropped: ~146 call sites pass
// `t(key, language)` with the value from useLanguageStore, and that store's type is now
// itself just "en" — removing the parameter here would mean touching every one of those.
export function t(key: TranslationKey, _language?: 'en'): string {
  return translations.en[key] || key;
}
